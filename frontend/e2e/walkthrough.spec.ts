import { test, expect } from '@playwright/test'

for (const width of [1440, 1024]) {
  test(`walkthrough teaches a database upgrade at ${width}px`, async ({ page }) => {
    const pageErrors: string[] = []
    page.on('pageerror', error => pageErrors.push(error.message))
    await page.setViewportSize({ width, height: width === 1440 ? 900 : 768 })
    await page.goto('/')
    await expect(page.locator('.challenge-card')).toHaveCount(5)
    const walkthrough = page.getByRole('article', { name: 'Your first design', exact: true })
    await expect(walkthrough).toBeVisible({ timeout: 5000 })
    await walkthrough.getByRole('button', { name: 'Start walkthrough' }).click()
    const guide = page.getByRole('dialog', { name: 'Getting started' })
    await expect(guide).toBeVisible()
    await page.screenshot({ path: `screenshots/walkthrough-guide-${width}.png`, fullPage: true })
    await guide.getByRole('button', { name: 'Open architecture' }).click()
    await expect(page.locator('.lab-node')).toHaveCount(3)
    await expect(page.getByRole('button', { name: 'Preview', exact: true })).toBeEnabled()
    await page.getByRole('button', { name: 'Preview', exact: true }).click()
    await expect(page.locator('.run-control')).toContainText('preview · completed')
    await expect(page.locator('.results-heading .status')).toHaveText(/incomplete/i)
    const latency = page.getByRole('table', { name: 'Requirement outcomes' }).getByRole('row').filter({ hasText: 'R02' })
    await expect(latency.locator('.status')).toHaveText(/fail/i)
    await latency.getByRole('button', { name: 'Inspect evidence' }).click()
    await expect(page.locator('.evidence-section')).toContainText('R02')
    await page.getByRole('button', { name: 'Guide', exact: true }).click()
    await expect(guide).toBeVisible()
    await guide.getByRole('button', { name: 'Open architecture' }).click()
    await page.locator('.lab-node').filter({ hasText: 'Database' }).click()
    const inspector = page.getByRole('complementary', { name: 'Inspector' })
    await inspector.getByRole('combobox', { name: 'Profile', exact: true }).selectOption('sql.medium.v1')
    await expect(page.locator('.revision-badge')).toContainText('Unassessed changes')
    await page.screenshot({ path: `screenshots/walkthrough-upgrade-${width}.png`, fullPage: true })
    const accepted = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/v1/runs'))
    await expect(page.getByRole('button', { name: 'Assess design' })).toBeEnabled()
    await page.getByRole('button', { name: 'Assess design' }).click()
    const { run_id } = await (await accepted).json()
    await expect(page.locator('.run-control')).toContainText('assessment · completed')
    await expect(page.locator('.results-heading .status')).toHaveText(/pass/i)
    await expect(page.locator('.requirement-row .status.pass')).toHaveCount(3)
    await page.screenshot({ path: `screenshots/walkthrough-pass-${width}.png`, fullPage: true })
    await page.getByRole('button', { name: 'Challenges', exact: true }).click()
    await expect(walkthrough.locator('.status')).toHaveText(/passed/i)
    await expect(page.locator('.challenge-card')).toHaveCount(5)
    await page.screenshot({ path: `screenshots/walkthrough-library-${width}.png`, fullPage: true })
    const collectionResponse = page.waitForResponse(response => response.url().endsWith('/api/v1/collection'))
    await page.getByRole('button', { name: 'Saved work', exact: true }).click()
    const collection: { items: { id: string; kind: string }[] } = await (await collectionResponse).json()
    const index = collection.items.findIndex(item => item.kind === 'run' && item.id === run_id)
    expect(index).toBeGreaterThanOrEqual(0)
    await page.locator('.history-row').nth(index).getByRole('button', { name: 'Open', exact: true }).click()
    await expect(page.locator('.workspace-identity h1')).toHaveText('Your first design')
    await expect(page.locator('.results-heading .status')).toHaveText(/pass/i)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
    expect(pageErrors).toEqual([])
  })
}
