import { test, expect } from '@playwright/test'

for (const width of [1440, 1024]) {
  test(`spotlight guide builds and improves the first architecture at ${width}px`, async ({ page }) => {
    test.setTimeout(240_000)
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width, height: width === 1440 ? 900 : 768 })
    await page.goto('/')
    await expect(page.locator('.challenge-card')).toHaveCount(5)
    await page.getByRole('button', { name: 'Start walkthrough' }).click()
    await expect(page.locator('.lab-node')).toHaveCount(0)
    const guide = page.getByRole('dialog', { name: 'First design guide' })
    await expect(guide).toHaveAttribute('data-step', 'client')
    await page.screenshot({ path: `screenshots/interactive-guide-start-${width}.png`, fullPage: true })
    for (const type of ['client', 'app_service', 'sql_database']) {
      const target = page.locator(`[data-guide="add-${type}"]`)
      await expect(target).toBeVisible()
      if (width === 1024) await target.press('Enter')
      else await target.click()
    }
    await expect(page.locator('.lab-node')).toHaveCount(3)
    const inspector = page.getByRole('complementary', { name: 'Inspector' })
    for (const [source, target] of [['Client', 'App service'], ['App service', 'SQL database']]) {
      await inspector.getByRole('combobox', { name: 'From', exact: true }).selectOption({ label: source })
      await inspector.getByRole('combobox', { name: 'To', exact: true }).selectOption({ label: target })
      await inspector.getByRole('checkbox', { name: 'read_note' }).check()
      await inspector.getByRole('button', { name: 'Add connection', exact: true }).press('Enter')
    }
    await expect(guide).toHaveAttribute('data-step', 'requirements')
    await page.getByRole('tab', { name: 'Requirements' }).click()
    await guide.getByRole('button', { name: 'Continue to Preview' }).click()
    await page.getByRole('button', { name: 'Preview', exact: true }).click()
    await expect(page.locator('.run-control')).toContainText('preview · completed', { timeout: 120_000 })
    await expect(guide).toHaveAttribute('data-step', 'flow')
    await expect(page.locator('.trace-events')).toContainText('SQL database')
    await expect(page.locator('.recorded-node')).toHaveCount(3)
    await expect(page.locator('.recorded-node').first()).toBeInViewport()
    await expect(page.locator('.recorded-node').last()).toBeInViewport()
    await page.getByRole('button', { name: 'Play replay' }).click()
    await page.screenshot({ path: `screenshots/interactive-guide-flow-${width}.png`, fullPage: false })
    await expect(guide).toHaveAttribute('data-step', 'evidence', { timeout: 45_000 })
    const latency = page.getByRole('table', { name: 'Requirement outcomes' }).getByRole('row').filter({ hasText: 'R02' })
    await expect(latency.locator('.status')).toHaveText(/fail/i)
    await latency.getByRole('button', { name: 'Inspect evidence' }).click()
    await expect(guide).toHaveAttribute('data-step', 'upgrade')
    await expect(page.locator('.evidence-section')).toContainText('R02')
    await page.getByRole('tab', { name: 'Architecture' }).click()
    await inspector.getByRole('combobox', { name: 'Profile', exact: true }).selectOption('sql.medium.v1')
    await expect(guide).toHaveAttribute('data-step', 'assessment')
    await page.screenshot({ path: `screenshots/interactive-guide-upgrade-${width}.png`, fullPage: true })
    const accepted = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/v1/runs'))
    await page.getByRole('button', { name: 'Assess design' }).click()
    const { run_id } = await (await accepted).json()
    await expect(page.locator('.run-control')).toContainText('assessment · completed', { timeout: 120_000 })
    await expect(guide).toHaveAttribute('data-step', 'complete')
    await expect(page.locator('.requirement-row .status.pass')).toHaveCount(3)
    await page.screenshot({ path: `screenshots/interactive-guide-pass-${width}.png`, fullPage: true })
    const collectionResponse = page.waitForResponse(response => response.url().endsWith('/api/v1/collection'))
    await page.getByRole('button', { name: 'Saved work', exact: true }).click()
    const collection = await (await collectionResponse).json()
    const index = collection.items.findIndex((item: { id: string }) => item.id === run_id)
    await page.locator('.history-row').nth(index).getByRole('button', { name: 'Open', exact: true }).click()
    await page.getByRole('button', { name: 'Resume guide', exact: true }).click()
    await expect(guide).toHaveAttribute('data-step', 'complete')
    await guide.getByRole('button', { name: 'Finish guide' }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
    expect(errors).toEqual([])
  })
}

test('guide ignores wrong actions, recovers after undo, and skip/resume preserves the draft', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Start walkthrough' }).click()
  const guide = page.getByRole('dialog', { name: 'First design guide' })
  await page.locator('[data-guide="add-sql_database"]').click()
  await expect(guide).toHaveAttribute('data-step', 'client')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await page.locator('[data-guide="add-client"]').click()
  await expect(guide).toHaveAttribute('data-step', 'app')
  await guide.getByRole('button', { name: 'Skip guide' }).click()
  await expect(guide).not.toBeVisible()
  await expect(page.locator('.lab-node')).toHaveCount(1)
  await page.getByRole('button', { name: 'Resume guide', exact: true }).click()
  await expect(guide).toHaveAttribute('data-step', 'app')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(guide).toHaveAttribute('data-step', 'client')
  await page.locator('[data-guide="add-client"]').click()
  page.once('dialog', dialog => dialog.dismiss())
  await guide.getByRole('button', { name: 'Restart walkthrough' }).click()
  await expect(page.locator('.lab-node')).toHaveCount(1)
  page.once('dialog', dialog => dialog.accept())
  await guide.getByRole('button', { name: 'Restart walkthrough' }).click()
  await expect(page.locator('.lab-node')).toHaveCount(0)
  await expect(guide).toHaveAttribute('data-step', 'client')
})

test('keyboard users can add components and connect a route through the highlighted controls', async ({ page }) => {
  await page.setViewportSize({ width: 1024, height: 768 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Start walkthrough' }).click()
  for (const type of ['client', 'app_service', 'sql_database']) {
    await expect(page.locator(`[data-guide="add-${type}"]`)).toBeFocused()
    await page.keyboard.press('Enter')
  }
  const inspector = page.getByRole('complementary', { name: 'Inspector' })
  const source = inspector.getByRole('combobox', { name: 'From', exact: true })
  await expect(source).toBeFocused()
  await page.keyboard.press('c')
  await page.keyboard.press('Tab')
  await page.keyboard.press('a')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Space')
  await page.keyboard.press('Tab')
  await expect(inspector.getByRole('button', { name: 'Add connection', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog', { name: 'First design guide' })).toHaveAttribute('data-step', 'database-route')
})
