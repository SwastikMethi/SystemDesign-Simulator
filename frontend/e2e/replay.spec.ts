import { test, expect, type Page } from '@playwright/test'

async function openRecording(page: Page) {
  const fixture = await (await page.request.get('/api/v1/challenges/first-design/fixtures/reference')).json()
  const created = await (await page.request.post('/api/v1/designs', { data: { challenge_id: fixture.challenge_id, challenge_version: fixture.challenge_version, nodes: fixture.nodes, edges: fixture.edges } })).json()
  const response = await page.request.post('/api/v1/runs', { data: { design_id: created.design_id, revision_id: created.revision.revision_id, challenge_id: fixture.challenge_id, challenge_version: fixture.challenge_version, mode: 'assessment' } })
  expect(response.ok()).toBeTruthy()
  const { run_id } = await response.json()
  await expect.poll(async () => (await (await page.request.get(`/api/v1/runs/${run_id}`)).json()).execution_status, { timeout: 120_000 }).toBe('completed')
  const results = await (await page.request.get(`/api/v1/runs/${run_id}/results`)).json()
  await page.goto('/')
  const collectionResponse = page.waitForResponse(response => response.url().endsWith('/api/v1/collection'))
  await page.getByRole('button', { name: 'Saved work', exact: true }).click()
  const collection = await (await collectionResponse).json()
  const index = collection.items.findIndex((item: { id: string }) => item.id === run_id)
  await page.locator('.history-row').nth(index).getByRole('button', { name: 'Open', exact: true }).click()
  return { run_id, recordedCase: results.assessment.case_results[0] }
}

test('request replay starts ready, shows motion, pauses, steps and restarts at its own boundary', async ({ page }) => {
  const { recordedCase } = await openRecording(page)
  await expect(page.getByRole('combobox', { name: 'Trace', exact: true })).toHaveValue(recordedCase.trace_refs[0])
  await expect(page.getByRole('combobox', { name: 'Speed', exact: true })).toHaveValue('teaching')
  const slider = page.getByRole('slider', { name: 'Replay position' })
  await expect(page.locator('.replay-explanation')).not.toBeEmpty()
  const min = Number(await slider.getAttribute('min')), max = Number(await slider.getAttribute('max'))
  expect(min).toBeGreaterThan(0)
  expect(max - min).toBeLessThan(250_000)
  await page.getByRole('button', { name: 'Play replay' }).click()
  await expect(page.locator('.recorded-marker')).toBeVisible({ timeout: 1000 })
  await expect.poll(async () => Number(await slider.inputValue()), { timeout: 1500 }).toBeGreaterThan(min)
  await page.getByRole('button', { name: 'Pause replay' }).click()
  const paused = Number(await slider.inputValue())
  await page.waitForTimeout(150)
  expect(Number(await slider.inputValue())).toBe(paused)
  await page.getByRole('button', { name: 'Next frame' }).click()
  expect(Number(await slider.inputValue())).toBeGreaterThan(paused)
  await page.locator('.trace-events button').filter({ hasText: 'response sent' }).first().click()
  await expect(page.locator('.replay-explanation')).toContainText('sends its response back')
  const returnStart = Number(await page.locator('.recorded-marker').getAttribute('cx'))
  await page.getByRole('button', { name: 'Play replay' }).click()
  await page.waitForTimeout(200)
  await page.getByRole('button', { name: 'Pause replay' }).click()
  expect(Number(await page.locator('.recorded-marker').getAttribute('cx'))).toBeLessThan(returnStart)
  await slider.fill(String(max))
  await expect(page.locator('.replay-explanation')).toContainText(/success|response returned/i)
  await page.getByRole('button', { name: 'Play replay' }).click()
  await expect(page.getByRole('button', { name: 'Pause replay' })).toBeVisible()
  expect(Number(await slider.inputValue())).toBeLessThan(max)
  await page.getByRole('button', { name: 'Pause replay' }).click()
  await page.getByRole('combobox', { name: 'Trace', exact: true }).selectOption('')
  await expect(slider).toHaveAttribute('min', '0')
  expect(Number(await slider.getAttribute('max'))).toBeGreaterThan(max)
})

test('request replay retries missing recordings and keeps reduced motion usable', async ({ page }) => {
  let fail = true
  await page.route('**/cases/*/traces/*', async route => {
    if (fail) return route.fulfill({ status: 503, json: { error: { code: 'unavailable', message: 'Recording unavailable' } } })
    return route.continue()
  })
  await openRecording(page)
  await expect(page.getByRole('button', { name: 'Play replay' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Retry recording' })).toBeVisible()
  fail = false
  await page.getByRole('button', { name: 'Retry recording' }).click()
  await expect(page.getByRole('button', { name: 'Play replay' })).toBeEnabled()
  await page.getByRole('checkbox', { name: 'Reduced motion' }).check()
  await page.getByRole('button', { name: 'Next frame' }).click()
  await expect(page.locator('.recorded-marker')).toHaveCount(0)
  await expect(page.locator('.replay-explanation')).not.toBeEmpty()
  await expect(page.locator('.recorded-legend')).toContainText('Reduced motion')
  await page.route('**/cases/*/traces/*', async route => {
    const response = await route.fetch()
    await route.fulfill({ json: { ...await response.json(), events: [] } })
  })
  await page.getByRole('combobox', { name: 'Trace', exact: true }).selectOption({ index: 2 })
  await expect(page.getByText('This request has no recorded events.', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Play replay' })).toBeDisabled()
})
